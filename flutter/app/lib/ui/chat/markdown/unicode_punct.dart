/// Whether the UTF-16 code unit [char] is a Unicode punctuation or symbol
/// codepoint (BMP only; surrogate halves are not).
bool isPunctOrSymbol(int char) {
  var low = 0;
  var high = kPunctSymbolRanges.length - 1;
  while (low <= high) {
    final mid = (low + high) >> 1;
    final (start, end) = kPunctSymbolRanges[mid];
    if (char < start) {
      high = mid - 1;
    } else if (char > end) {
      low = mid + 1;
    } else {
      return true;
    }
  }
  return false;
}
